interface LanguageContextValue {
  language: Language;
  setLanguage: (language: Language) => void;
  toggleLanguage: () => void;
  t: (vietnamese: string) => string;
}

const LanguageContext = createContext<LanguageContextValue | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(() => {
    const stored = window.localStorage.getItem('uptime-watch-language');
    return stored === 'en' ? 'en' : 'vi';
  });

  const setLanguage = (nextLanguage: Language) => {
    window.localStorage.setItem('uptime-watch-language', nextLanguage);
    setLanguageState(nextLanguage);
  };
  const toggleLanguage = () => setLanguage(language === 'vi' ? 'en' : 'vi');
  const t = (vietnamese: string) => language === 'vi' ? vietnamese : translations[vietnamese] ?? vietnamese;

  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);

  const value = useMemo(() => ({ language, setLanguage, toggleLanguage, t }), [language]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error('useLanguage must be used within LanguageProvider.');
  return context;
}

export function LanguageToggle() {
  const { language, toggleLanguage } = useLanguage();
  const label = language === 'vi' ? 'Chuyển sang tiếng Anh' : 'Switch to Vietnamese';
  return (
    <button
      type="button"
      className="language-toggle"
      onClick={toggleLanguage}
      aria-label={label}
      title={label}
    >
      {language === 'vi' ? 'EN' : 'VN'}
    </button>
  );
}
